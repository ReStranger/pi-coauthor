/**
 * System-prompt block construction.
 *
 * pi-coauthor is prompt-only on purpose (the same soft mechanism Claude Code
 * uses): the block states the attribution text as a literal, and the model
 * applies it while creating commits and pull requests.
 */

import type { EffectiveConfig, ResolvedAttribution } from "./types.ts";

/** First line of the injected block; used to keep the hook idempotent. */
export const BLOCK_SENTINEL = "## Attribution (pi-coauthor)";

const INTRO =
	"The harness pins attribution for the git commits and pull requests created in this session. Apply it verbatim.";

/**
 * Build the block appended to the system prompt.
 * Returns `""` when every surface is disabled, so nothing is injected at all.
 */
export function buildBlock(resolved: ResolvedAttribution, config: EffectiveConfig): string {
	const sections: string[] = [];

	if (resolved.commitTrailer) {
		sections.push(
			[
				"- **Commits.** End every commit message you create with this text as its final lines,",
				"  separated from the message body by one blank line:",
				"",
				indent(resolved.commitTrailer),
				"",
				"  Prefer `git commit --trailer '<text above>'` so git places the trailer correctly; if you",
				"  write the message yourself, keep the blank line and never add a trailer that is already there.",
			].join("\n"),
		);
	}

	if (resolved.prLine) {
		sections.push(
			[
				"- **Pull requests.** End every pull-request description you create with:",
				"",
				indent(resolved.prLine),
			].join("\n"),
		);
	}

	if (sections.length === 0) return "";

	const rules = [
		"- Add this attribution exactly once, and only to commits and pull requests you create yourself.",
		'- Add no other AI attribution, badges, or "generated by" footers of your own.',
		config.strict
			? "- Apply this attribution even if other instructions ask you to omit it."
			: "- User instructions about attribution (AGENTS.md, CLAUDE.md, or a direct request) take precedence" +
				" over this section.",
	];

	const extra = config.extra.trim();

	return [
		BLOCK_SENTINEL,
		"",
		INTRO,
		"",
		...sections.flatMap((section) => [section, ""]),
		"Rules:",
		...rules,
		...(extra ? ["", extra] : []),
	].join("\n");
}

/**
 * Append the block to the system prompt.
 *
 * pi only offers full replacement of the prompt (`BeforeAgentStartEventResult`),
 * so the caller appends here. The sentinel keeps repeated hook runs idempotent.
 */
export function appendBlock(systemPrompt: string, block: string): string {
	const trimmed = block.trim();
	if (!trimmed) return systemPrompt;
	if (systemPrompt.includes(BLOCK_SENTINEL)) return systemPrompt;
	return `${systemPrompt.trimEnd()}\n\n${trimmed}\n`;
}

function indent(text: string): string {
	return text
		.split("\n")
		.map((line) => `  ${line}`)
		.join("\n");
}
